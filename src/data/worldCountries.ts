export function findCountryByCoords(lat: number, lng: number): Country | null {
  let closest: Country | null = null;
  let minDist = Infinity;
  for (const c of worldCountries) {
    const d = Math.sqrt((c.lat - lat) ** 2 + (c.lng - lng) ** 2);
    if (d < minDist) {
      minDist = d;
      closest = c;
    }
  }
  return closest;
}
